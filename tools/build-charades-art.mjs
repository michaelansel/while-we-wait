#!/usr/bin/env node
/*
 * Builds charades-art.js: the OpenMoji SVGs referenced by `art:'HEX'` fields
 * in games.js, minified into one offline-cacheable file.
 *
 *   node tools/build-charades-art.mjs
 *
 * Dev-time only — the app itself has no build step; the output is committed.
 * Art: OpenMoji (https://openmoji.org), CC BY-SA 4.0.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const VERSION = '15.1.0';
const SRC = hex => `https://cdn.jsdelivr.net/npm/openmoji@${VERSION}/color/svg/${hex}.svg`;
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const games = await readFile(join(root, 'games.js'), 'utf8');
const hexes = [...new Set([...games.matchAll(/\bart:\s*'([0-9A-F-]+)'/g)].map(m => m[1]))].sort();
console.log(`${hexes.length} unique art hexcodes in games.js`);

// Round long decimals to 1 place (viewBox is 72 units, so 0.05 is invisible).
// Insert a space when the previous char is a digit/dot so "1.23.45" stays two numbers.
function shrinkNumbers(s) {
  return s.replace(/-?\d*\.\d+/g, (m, off, str) => {
    let r = String(Math.round(parseFloat(m) * 10) / 10);
    if (r === '-0') r = '0';
    const prev = str[off - 1];
    return (prev && /[\d.]/.test(prev) ? ' ' : '') + r;
  });
}

function minify(svg, hex) {
  const ns = `om${hex.replace(/-/g, '')}-`;
  return shrinkNumbers(svg
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .replace(/>\s+</g, '><')
    .replace(/\s+(version|xml:space)="[^"]*"/g, '')
    // namespace ids so several inlined SVGs never collide
    .replace(/\bid="([^"]+)"/g, (_, id) => `id="${ns}${id}"`)
    .replace(/url\(#([^)]+)\)/g, (_, id) => `url(#${ns}${id})`)
    .replace(/href="#([^"]+)"/g, (_, id) => `href="#${ns}${id}"`)
    .trim());
}

const out = {};
const missing = [];
await Promise.all(hexes.map(async hex => {
  const res = await fetch(SRC(hex));
  if (!res.ok) { missing.push(`${hex} (HTTP ${res.status})`); return; }
  out[hex] = minify(await res.text(), hex);
}));
if (missing.length) {
  console.error(`Missing OpenMoji art:\n  ${missing.join('\n  ')}`);
  process.exit(1);
}

const body = hexes.map(h => `${JSON.stringify(h)}:${JSON.stringify(out[h])}`).join(',\n');
const js = `/* Generated by tools/build-charades-art.mjs — do not edit by hand.
   Art: OpenMoji ${VERSION} (https://openmoji.org), CC BY-SA 4.0. */
const ART = {
${body}
};
`;
await writeFile(join(root, 'charades-art.js'), js);
console.log(`Wrote charades-art.js (${hexes.length} icons, ${(js.length / 1024).toFixed(0)} KB)`);
